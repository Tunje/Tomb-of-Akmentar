def companion_card(who, name, alive, dead, never):
    """alive: [(id, if, caption, text)], tried in order, all with in_party added; dead: (caption, text); never: (caption, text)."""
    vs = []
    for id_, cond, cap, text in alive:
        c = {"in_party": who}
        c.update(cond)
