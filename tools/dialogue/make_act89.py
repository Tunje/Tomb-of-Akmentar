def first_of(ids, prefix, then_none):
    return B(*[({"in_party": i}, "%s_%s" % (prefix, i)) for i in ids], (None, then_none))


def pick_companion(nodes, prefix, question, effects_for, then, none_label=None, say="%s."):
    """A grouped picker (the wheel never holds more than 6): a menu of the four groups, each a menu of
    the companions in the party; picking one applies effects_for(id) and goes to `then`."""
    menu = []
    for k, (label, ids) in enumerate(GROUPS):
        gid = "%s_g%d" % (prefix, k)
        menu.append(C(label, "", gid))
        nodes[gid] = L("player", question, choices=[
            C(SHORT[i], say % SHORT[i], then, if_={"in_party": i}, do=effects_for(i)) for i in ids] + [C("Back", "", prefix)])
    if none_label:
        menu.append(C(none_label[0], none_label[1], then, do=none_label[2]))
    nodes[prefix] = L("player", question, choices=menu)
    return prefix


def spot(name, prompt, actions, help_text):
    return {"_help": help_text + " See scripts/actions/action_spot.gd for the format. Generated by tools/dialogue/make_act89.py.",
            "name": name, "prompt": prompt, "actions": actions}


def buy(id_, label, price, do, once=False, if_=None):
    cond = {"money": price}
    cond.update(if_ or {})
    a = {"id": id_, "label": "%s (£%d)" % (label, price), "cost": 0, "if": cond, "do": [pay(price)] + do, "log": label}
    if once:
        a["once"] = True
    return a


