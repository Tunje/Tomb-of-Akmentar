def check_epilogue(problems):
    from dlg import CONDS
    for c in CARDS:
        vs = c["variants"]
        if vs[-1].get("if"):
            problems.append("epilogue %s: the last variant has a condition" % c["who"])
        for v in vs:
            for k in v.get("if", {}):
                if k not in CONDS:
                    problems.append("epilogue %s/%s: unknown condition %s" % (c["who"], v["id"], k))


