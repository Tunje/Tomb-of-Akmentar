def plan_found(t, source):
    return [flag("thieves_plan_known"), {"journal": ["act7_cairo", "plan_" + t, source]}]


def investigation(host, open_line, found, not_here, extra_choices=None, extra_nodes=None):
    """A spot's talk: the host's line, then their answer depends on who the thieves are: found[t] =
    (line, effects) for the thieves this spot knows about, not_here = the line for the others."""
    n = {"start": L(host, open_line, "answer")}
    n["answer"] = B(*[({"flag": "thieves_" + t}, "a_" + t) for t in THIEVES if t in found], (None, "a_none"))
    for t, (line, fx) in found.items():
        n["a_" + t] = L(host, line, "more", do=fx)
    n["a_none"] = L(host, not_here, "more")
    choices = (extra_choices or []) + [C("Leave", "Thank you.", "end")]
    n["more"] = L(host, "Anything else?", choices=choices)
    n.update(extra_nodes or {})
    n["end"] = END
    return n


