def spot(name, prompt, actions, help_text):
    return {"_help": help_text + " See scripts/actions/action_spot.gd for the format. Generated by tools/dialogue/make_act67.py.",
            "name": name, "prompt": prompt, "actions": actions}


def act(id_, label, conversation, with_, log, cost=1, if_=None, once=True, locked=None, hide=False):
    a = {"id": id_, "label": label, "cost": cost, "conversation": conversation, "log": log}
    if with_:
        a["with"] = with_
    if once:
        a["once"] = True
    if if_:
        a["if"] = if_
    if locked:
        a["locked_text"] = locked
    if hide:
        a["hide_if_locked"] = True
    return a


